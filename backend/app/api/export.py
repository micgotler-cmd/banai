"""Carpenter PDF export: the client sends its committed design (and optionally the app's own 3D
snapshot of it), the server validates both and returns the PDF. Nothing is stored and no AI is
involved. The snapshot is generated by the app, not uploaded by the customer."""

from __future__ import annotations

import json
from datetime import date
from typing import Annotated, Literal

from fastapi import APIRouter, Request
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import Response
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from app.api.agent import error
from app.domain.apply import apply_ops
from app.domain.catalog import load_catalog
from app.domain.errors import DomainError
from app.export.image import InvalidImage, clean_snapshot
from app.export.pdf import render_pdf

router = APIRouter(prefix="/api")

# A maximal valid design (20 compartments, 300 items, long custom names) is under 256 kB; the
# optional snapshot adds at most about 2.7 MB of base64.
MAX_BODY_BYTES = 3_000_000
# A worst-case render takes about 1 s of CPU; cap concurrent renders per worker so a burst of
# exports can't drain the shared threadpool used by every other endpoint.
MAX_CONCURRENT_RENDERS = 2
_active_renders = 0  # only touched on the event loop thread

MESSAGES = {
    "INVALID_REQUEST": {"he": "הבקשה אינה תקינה.", "en": "The request is not valid."},
    "TOO_LARGE": {"he": "העיצוב גדול מדי לייצוא.", "en": "The design is too large to export."},
    "INVALID_IMAGE": {"he": "תמונת הארון אינה תקינה.", "en": "The wardrobe picture is not valid."},
    "BUSY": {"he": "השרת עסוק בהכנת קבצים אחרים. נסה שוב בעוד רגע.", "en": "The server is busy preparing other files. Please try again in a moment."},
}


class ExportRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    design: dict
    language: Literal["he", "en"] = "he"
    image: Annotated[str, Field(max_length=2_700_000)] | None = None  # data:image/(png|jpeg);base64,...


async def read_capped(request: Request, limit: int = MAX_BODY_BYTES) -> bytes | None:
    """The body, or None once it passes `limit` bytes (stops reading early)."""
    chunks, size = [], 0
    async for chunk in request.stream():
        size += len(chunk)
        if size > limit:
            return None
        chunks.append(chunk)
    return b"".join(chunks)


def _build(design: dict, catalog: dict, language: str, image: str | None) -> bytes:
    snapshot = clean_snapshot(image) if image else None
    return render_pdf(design, catalog, language, date.today(), snapshot=snapshot)


@router.post("/export/pdf")
async def export_pdf(request: Request):
    body = await read_capped(request)
    if body is None:
        return error(413, "TOO_LARGE", MESSAGES["TOO_LARGE"]["he"])
    try:
        raw = json.loads(body)
    except (ValueError, RecursionError):  # RecursionError: deeply nested arrays
        raw = None
    language = raw.get("language") if isinstance(raw, dict) and raw.get("language") in ("he", "en") else "he"
    try:
        parsed = ExportRequest.model_validate(raw)
    except ValidationError:
        return error(422, "INVALID_REQUEST", MESSAGES["INVALID_REQUEST"][language])
    catalog = load_catalog()
    try:
        design = apply_ops(parsed.design, [], catalog)  # parse + fully validate, no ops
    except DomainError as exc:
        return error(422, exc.code, exc.message, exc.path)
    global _active_renders
    if _active_renders >= MAX_CONCURRENT_RENDERS:
        response = error(503, "BUSY", MESSAGES["BUSY"][parsed.language])
        response.headers["Retry-After"] = "2"
        return response
    _active_renders += 1
    try:
        # CPU-bound (image decode + render): keep it off the event loop.
        pdf = await run_in_threadpool(_build, design, catalog, parsed.language, parsed.image)
    except InvalidImage:
        return error(422, "INVALID_IMAGE", MESSAGES["INVALID_IMAGE"][parsed.language], "image")
    finally:
        _active_renders -= 1
    dims = design["dimensions"]
    filename = f"banai-wardrobe-{dims['width']}x{dims['height']}x{dims['depth']}mm.pdf"
    return Response(pdf, media_type="application/pdf", headers={
        "Content-Disposition": f'attachment; filename="{filename}"',
        "Cache-Control": "no-store",
        "X-Content-Type-Options": "nosniff",
    })
